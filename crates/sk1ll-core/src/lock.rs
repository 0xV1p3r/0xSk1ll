use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::{Error, IoExt, Result};

pub const LOCK_FILE: &str = "sk1ll.lock";

/// `sk1ll.lock`: the exact commit and content hash each import was vendored at.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Lockfile {
    #[serde(default)]
    pub skills: BTreeMap<String, LockEntry>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockEntry {
    pub source: String,
    #[serde(default)]
    pub path: String,
    #[serde(rename = "ref")]
    pub git_ref: String,
    pub commit: String,
    pub hash: String,
}

impl Lockfile {
    pub fn load(root: &Path) -> Result<Self> {
        let path = root.join(LOCK_FILE);
        if !path.exists() {
            return Ok(Self::default());
        }
        let text = fs::read_to_string(&path).at(&path)?;
        toml::from_str(&text).map_err(|e| Error::Parse { path, message: e.to_string() })
    }

    pub fn save(&self, root: &Path) -> Result<()> {
        let path = root.join(LOCK_FILE);
        let body = toml::to_string_pretty(self)
            .map_err(|e| Error::Parse { path: path.clone(), message: e.to_string() })?;
        fs::write(&path, format!("# Generated by 0xSk1ll. Do not edit by hand.\n\n{body}")).at(&path)
    }
}
